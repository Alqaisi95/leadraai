/**
 * The Worker entry point.
 *
 * OpenNext compiles the Next app into `.open-next/worker.js`, which exports a
 * `fetch` handler and nothing else. Cloudflare Cron Triggers need a
 * `scheduled` handler, so this wraps the generated worker and adds one.
 *
 * The two jobs stay where they already are — `/api/worker/drain` and
 * `/api/worker/jobs`, both authenticated with CRON_SECRET. Rather than reach
 * into the app's internals, `scheduled` calls the generated handler with a
 * synthetic request. That keeps a single implementation of each job, exercised
 * identically whether a cron or an operator triggers it, and it costs no
 * network hop: the call never leaves the isolate.
 *
 * The spread of the generated worker's other exports matters. OpenNext emits
 * Durable Object classes for its queue and cache, and Wrangler resolves the
 * `durable_objects` bindings against this module — dropping them here would
 * break deployment with an error that points at the bindings rather than here.
 */
// @ts-ignore — generated by `opennextjs-cloudflare build`; may or may not exist at check time
import openNextWorker from "./.open-next/worker.js";

// @ts-ignore — same generated module; re-exports the Durable Object classes
export * from "./.open-next/worker.js";

interface CronEnv {
  CRON_SECRET?: string;
}

/**
 * The two Workers runtime types this file needs, declared locally.
 *
 * Adding @cloudflare/workers-types to tsconfig's `types` would be the usual
 * route, but TypeScript applies that program-wide: the Workers globals would
 * then shadow the DOM's Request, Response and caches across the whole Next
 * app, which is built against `lib: ["dom", ...]`. Two small interfaces are a
 * far smaller price than that ambiguity.
 */
interface ScheduledController {
  readonly cron: string;
  readonly scheduledTime: number;
}
interface ExecutionContext {
  waitUntil(promise: Promise<unknown>): void;
  passThroughOnException(): void;
}

/** Which path each cron expression drives. Must match `triggers.crons` in wrangler.jsonc. */
const SCHEDULE_ROUTES: Record<string, string> = {
  "* * * * *": "/api/worker/drain",
  "0 * * * *": "/api/worker/jobs",
};

export default {
  fetch: openNextWorker.fetch,

  async scheduled(controller: ScheduledController, env: CronEnv, ctx: ExecutionContext) {
    const path = SCHEDULE_ROUTES[controller.cron];
    if (!path) {
      console.error("cron_unmapped", controller.cron);
      return;
    }
    if (!env.CRON_SECRET) {
      // Both routes answer 401 without it, so the job would silently never run.
      console.error("cron_missing_secret", path);
      return;
    }

    // The host is arbitrary — the request is handled in-process and never sent.
    const request = new Request(`https://cron.invalid${path}`, {
      method: "GET",
      headers: { authorization: `Bearer ${env.CRON_SECRET}` },
    });

    const run = (async () => {
      try {
        const response = await openNextWorker.fetch(request, env, ctx);
        // Only failures are logged here. A successful run already records
        // itself in job_runs, which is the durable record an operator reads;
        // a second copy in the Worker log would just drift from it.
        if (!response.ok) {
          const body = await response.text();
          console.error("cron_failed", path, response.status, body.slice(0, 300));
        }
      } catch (e) {
        console.error("cron_threw", path, String(e).slice(0, 300));
      }
    })();

    // waitUntil, so a job outliving the scheduled callback still completes.
    ctx.waitUntil(run);
    await run;
  },
};
